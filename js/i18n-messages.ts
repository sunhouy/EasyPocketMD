export function uiText(message: string): string {
    const i18n = typeof window === 'undefined' ? undefined : window.i18n;
    if (i18n?.has?.('ui:' + message)) return i18n.t('ui:' + message);
    return i18n?.getLanguage?.() === 'en' ? (uiMessages[message] || message) : message;
}

/** Keep button labels and accessibility text translatable after a language switch. */
export function setUiText(element: HTMLElement, value: string, attribute = 'textContent') {
    const source = Object.hasOwn(uiMessages, value) ? value : Object.keys(uiMessages).find(key => uiMessages[key] === value);
    if (source) element.setAttribute(attribute === 'textContent' ? 'data-i18n' : 'data-i18n-' + attribute, 'ui:' + source);
    if (attribute === 'textContent') element.textContent = value;
    else element.setAttribute(attribute, value);
}
